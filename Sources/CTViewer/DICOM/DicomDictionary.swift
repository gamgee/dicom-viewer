    private static func key(_ tag: DicomTag) -> UInt32 { UInt32(tag.group) << 16 | UInt32(tag.element) }

    static func vr(for tag: DicomTag) -> String? {
        if tag.element == 0x0000 { return "UL" }
        if tag.group % 2 == 1, (0x0010...0x00FF).contains(tag.element) { return "LO" }
        return entries[key(tag)]?.vr
    }

    static func name(for tag: DicomTag) -> String {
        if let name = entries[key(tag)]?.name { return name }
        if tag.element == 0x0000 { return "Group Length" }
        if tag.group % 2 == 1 {
            return (0x0010...0x00FF).contains(tag.element) ? "Private Creator" : "Private Tag"
        }
        return "Unknown"
    }
